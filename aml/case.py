"""SAR-style case summary (template, no LLM). One markdown file per prioritised customer case."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

TEMPLATE = """# Case {case_id}: {customer_name} ({customer_id})

**Priority:** {priority} (score {score})   **Rules triggered:** {rules}   **Review period:** {period}

## Subject
- Customer type: {customer_type}; risk rating at onboarding: {risk_rating}; occupation: {occupation}; country: {country}
- Onboarded: {onboarding_date}; expected monthly volume: ${expected:,.0f}
- Accounts: {accounts}

## Summary of activity
Over the review period the subject conducted {n_txns:,} transactions totalling ${total:,.0f} ({n_in:,} inbound / ${total_in:,.0f}; {n_out:,} outbound / ${total_out:,.0f}).
Activity flagged by monitoring totals ${flagged_total:,.0f} across {n_alerts} alert(s).

## Suspicious activity (by alert)
{alert_lines}

## Why this may be suspicious
{why}

## Recommendation
{recommendation}

*Generated by aml-transaction-monitoring from synthetic data - not a real SAR.*
"""

WHY = {
    "R1_structuring": "Cash deposits are repeatedly kept just under the $10,000 currency transaction reporting threshold, a pattern consistent with structuring to avoid a CTR (31 U.S.C. 5324).",
    "R2_rapid_movement": "Funds leave the account almost as soon as they arrive, with little economic purpose evident - consistent with pass-through / layering activity.",
    "R3_round_dollar": "Transfers cluster on exact round-thousand amounts, which is atypical for commercial or payroll activity and common in layering.",
    "R4_dormant_reactivation": "A long-dormant relationship abruptly moves substantial funds, which can indicate account takeover or use of a stale account as a conduit.",
    "R5_geo_velocity": "Card activity in two countries within hours is physically implausible for a single cardholder and suggests card cloning or shared credentials.",
    "R6_high_risk_wire": "Outbound wires to a jurisdiction on the bank's high-risk list require enhanced due diligence on purpose and beneficiary.",
    "R7_cash_intensity": "Monthly cash deposits far exceed the volume the customer declared at onboarding.",
    "R8_velocity_spike": "Transaction count jumped several-fold over the customer's own baseline with no known business reason.",
}


def build_case(case_id: str, customer: pd.Series, accounts: pd.DataFrame, txns: pd.DataFrame, alerts: pd.DataFrame) -> str:
    alerts = alerts.sort_values("alert_date")
    period = f"{alerts.alert_date.min():%Y-%m-%d} to {alerts.alert_date.max():%Y-%m-%d}"
    flagged_ids = {t for ids in alerts.txn_ids for t in ids}
    inb = txns[txns.direction == "in"]; outb = txns[txns.direction == "out"]
    lines = "\n".join(f"- **{a.alert_date:%Y-%m-%d} {a.rule_id}** (score {a.score}): {a.detail}." for a in alerts.itertuples())
    why = "\n".join(f"- {WHY[r]}" for r in dict.fromkeys(alerts.rule_id))
    top = alerts.score.max()
    rec = ("File a SAR; escalate to the BSA officer." if top >= 60 else
           "Open an investigation and request supporting documentation (source of funds, purpose of transfers)." if top >= 35 else
           "Document review and close; add customer to a 90-day watch list.")
    return TEMPLATE.format(
        case_id=case_id, customer_name=customer.customer_name, customer_id=customer.customer_id, priority=alerts.priority.iloc[0], score=top,
        rules=", ".join(dict.fromkeys(alerts.rule_id)), period=period, customer_type=customer.customer_type, risk_rating=customer.risk_rating,
        occupation=customer.occupation, country=customer.country, onboarding_date=f"{pd.Timestamp(customer.onboarding_date):%Y-%m-%d}",
        expected=float(customer.expected_monthly_volume), accounts=", ".join(accounts.account_id + " (" + accounts.account_type + ")"),
        n_txns=len(txns), total=float(txns.amount.sum()), n_in=len(inb), total_in=float(inb.amount.sum()), n_out=len(outb), total_out=float(outb.amount.sum()),
        flagged_total=float(txns[txns.txn_id.isin(flagged_ids)].amount.sum()), n_alerts=len(alerts), alert_lines=lines, why=why, recommendation=rec)


def write_cases(out_dir: Path, scored: pd.DataFrame, customers: pd.DataFrame, accounts: pd.DataFrame, txns: pd.DataFrame, top_n: int = 25) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("case_*.md"):
        stale.unlink()
    top = scored.groupby("customer_id")["score"].max().sort_values(ascending=False).head(top_n)
    paths = []
    for i, cid in enumerate(top.index, 1):
        cust = customers.set_index("customer_id").loc[cid]
        cust["customer_id"] = cid
        text = build_case(f"{i:03d}", cust, accounts[accounts.customer_id == cid], txns[txns.customer_id == cid], scored[scored.customer_id == cid])
        p = out_dir / f"case_{i:03d}_{cid}.md"; p.write_text(text); paths.append(p)
    return paths
